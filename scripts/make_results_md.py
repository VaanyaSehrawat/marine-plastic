import json, pathlib

g = json.load(open("results/generative/generative_metrics.json"))
r = json.load(open("models/route/route_model_info.json"))
lat = json.load(open("results/java_latency.json"))
det, v, c, mt = g["detectors"], g["vae_vs_pca"], g["gan_copy_check"], r["metrics"]
o = []
w = o.append
w("# Results (generated by scripts/make_results_md.py from saved JSON files; do not edit by hand)\n")

w("## 1. Detectors (BePLi v2 official splits; 1280 px; conf 0.001; NMS IoU 0.6; max 400 detections)\n")
w("| Model | Split | Precision | Recall | mAP50 | mAP50-95 |")
w("|---|---|---:|---:|---:|---:|")
for m in ("YOLO11s", "YOLO11m"):
    for s in ("val", "test"):
        x = det[f"{m}_{s}"]
        w(f"| {m} | {s} | {x['P']:.3f} | {x['R']:.3f} | {x['mAP50']:.3f} | {x['mAP50_95']:.3f} |")
w("\nOne training run per model, so the YOLO11s / YOLO11m gap is a single-run difference, not a significance test. About 89% of annotated boxes are smaller than 32x32 px (dataset audit), which keeps absolute mAP low.\n")

w("### Java CPU inference time per image (ONNX Runtime 1.20.0, 1280 px input)\n")
w("| Image | " + " | ".join(lat["images"]) + " |")
w("|---|" + "---:|" * len(lat["images"]))
w("| YOLO11s (ms) | " + " | ".join(str(x) for x in lat["yolo11s_ms"]) + " |")
w("| YOLO11m (ms) | " + " | ".join(str(x) for x in lat["yolo11m_ms"]) + " |")
w(f"\nSource: {lat['source']}. Three images only; treat these as indicative.\n")

n = mt["random"][2]
w(f"## 2. Tile-priority ranking (test split, {n} images with at least 5 ground-truth tiles; 6x8 grid)\n")
w("| Method | Spearman | Top-5 overlap |")
w("|---|---:|---:|")
w(f"| random ranking | {mt['random'][0]:.3f} | {mt['random'][1]:.3f} |")
w(f"| detector-only planner score | {mt['detector_only'][0]:.3f} | {mt['detector_only'][1]:.3f} |")
for k, nm in (("tile_mlp", "tile MLP (no tile context)"), ("transformer", "route-context transformer")):
    s = mt[k]
    w(f"| {nm} ({s['params']:,} params) | {s['spearman_mean']:.3f} +- {s['spearman_std']:.3f} | {s['top5_mean']:.3f} +- {s['top5_std']:.3f} |")
gain = mt["transformer"]["spearman_mean"] - mt["tile_mlp"]["spearman_mean"]
sd = max(mt["transformer"]["spearman_std"], mt["tile_mlp"]["spearman_std"])
w(f"\nTransformer minus tile MLP: {gain:+.3f} Spearman (seed standard deviation about {sd:.3f}). Labels are ground-truth boxes weighted by the same class weights as the heuristic, so this measures agreement with a proxy, not real cleanup efficiency.\n")

w(f"## 3. VAE vs PCA ({v['latent_dim']} latent dims; {g['train_crops']} train crops, {g['val_crops']} held-out val crops; PCA output clipped to [0,1])\n")
w("| Measure | VAE | PCA |")
w("|---|---:|---:|")
w(f"| reconstruction MSE per pixel | {v['vae_mse']:.5f} | {v['pca_mse']:.5f} |")
w(f"| 5-NN class accuracy in latent space | {v['vae_knn_acc']:.3f} | {v['pca_knn_acc']:.3f} |")
w(f"\nTrain-majority-class baseline for 5-NN accuracy: {v['majority_train_class_on_val']:.3f}.")
w("Reconstruction: " + ("the VAE is better than PCA." if v["vae_mse"] < v["pca_mse"] else "the VAE is not better than PCA."))
w("Class information: " + ("both latent spaces score at or below the majority-class baseline, so they carry little class information at this setting."
   if max(v["vae_knn_acc"], v["pca_knn_acc"]) <= v["majority_train_class_on_val"] else "at least one latent space beats the majority-class baseline."))

w(f"\n## 4. DCGAN copy check ({c['epochs']} epochs; pixel-space L2 to the nearest training crop, scale [-1, 1])\n")
w("| | median | minimum |")
w("|---|---:|---:|")
w(f"| generated ({c['n_gen']} samples) | {c['gen_median']:.1f} | {c['gen_min']:.1f} |")
w(f"| real held-out val crops ({c['n_val']}) | {c['val_median']:.1f} | {c['val_min']:.1f} |")
fr = c["frac_gen_closer_than_every_val"]
w(f"\nShare of generated samples closer to a training crop than every real val crop: {fr*100:.1f}%. " +
  ("No sign of memorisation by this crude pixel-space check." if fr == 0 else "Some generated samples are unusually close to training crops; inspect them."))
w("No FID or other learned-feature metric was computed; sample quality is judged visually (results/generative/gan_samples.png).\n")

ck = g["checkpoints"]
w("## 5. Provenance\n")
for k in ("yolo11s", "yolo11m"):
    w(f"- {k}: SHA-256 {ck[k]['sha256']} (identical to the Mac/Java copy: {ck[k]['identical_to_mac_copy']})")
w("- Sources: results/generative/generative_metrics.json, results/detectors/detector_comparison.json, models/route/route_model_info.json, results/java_latency.json")
pathlib.Path("docs/RESULTS.md").write_text("\n".join(o) + "\n")
print("wrote docs/RESULTS.md")
