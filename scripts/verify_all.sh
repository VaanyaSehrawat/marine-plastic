#!/usr/bin/env bash
# One-command verification of the project. Place in ~/Projects/marine-plastic/scripts/ and run:
#   bash scripts/verify_all.sh
# Takes a few minutes. Every check logs to logs/verify/<name>.log; a summary is written to docs/VERIFICATION.md.
cd "$(dirname "${BASH_SOURCE[0]}")/.." || exit 1
mkdir -p logs/verify docs build
J=".tools/jdk-21/Contents/Home"
PY=".venv/bin/python"; [ -x "$PY" ] || PY=".tools/pybin/python3.12"; [ -x "$PY" ] || PY="python3"
STAMP="$(date '+%Y-%m-%d %H:%M')"
ROWS=""; NPASS=0; NFAIL=0; FAILED=""; T0=$SECONDS

# check <name> <description> <required output string or ""> <shell command string>
check() {
  local name="$1" desc="$2" need="$3" cmd="$4"
  local log="logs/verify/$name.log" t=$SECONDS
  printf "  %-26s " "$name"
  bash -c "$cmd" > "$log" 2>&1; local rc=$?
  local ok=0
  if [ $rc -eq 0 ]; then
    if [ -z "$need" ] || grep -q -- "$need" "$log"; then ok=1; fi
  fi
  local dt=$((SECONDS - t))
  if [ $ok -eq 1 ]; then NPASS=$((NPASS + 1)); echo "PASS (${dt}s)"; ROWS="$ROWS| $desc | PASS | ${dt} s |
"
  else NFAIL=$((NFAIL + 1)); FAILED="$FAILED $name"; echo "FAIL (${dt}s, exit $rc) -> logs/verify/$name.log"; ROWS="$ROWS| $desc | FAIL | ${dt} s |
"; fi
}

echo "== verification $STAMP =="
check py_tests        "Python tests and ONNX smoke test (M1-M2)"                    "ONNX smoke test PASSED" "source ./env.sh >/dev/null 2>&1; bash scripts/run_tests.sh"
check fundamentals    "Java fundamentals tests (tensor, SVD, MLP, optimizers, Oja, competitive)" "FUNDAMENTALS TEST: PASS" "$J/bin/javac -encoding UTF-8 -d java/out java/fundamentals/src/main/java/mp/fund/*.java && $J/bin/java -cp java/out mp.fund.FundamentalsTest"
check route_tests     "YOLO11m fixture test and route transformer test in Java"     "ROUTE TEST: PASS" "bash scripts/test_route.sh"
check selftest_m      "Dashboard self-test, YOLO11m with learned scoring"           "SELFTEST PASSED" "bash scripts/run_dashboard.sh --selftest"
check selftest_s      "Dashboard self-test, YOLO11s with heuristic scoring"         "SELFTEST PASSED" "bash scripts/run_app.sh --selftest"
check hashes_s        "SHA-256 of YOLO11s weights"                                  ": OK" "cd models/yolo11s_1280 && shasum -a 256 -c SHA256.txt"
check hashes_m        "SHA-256 of YOLO11m weights"                                  ": OK" "cd models/yolo11m_1280 && shasum -a 256 -c SHA256.txt"
check hashes_gen      "SHA-256 of VAE and GAN weights"                              ": OK" "cd results/generative/weights && shasum -a 256 -c SHA256.txt"
check planner_eval    "Planner evaluation re-run (includes Java parity gate)"       "PLANNER EVAL: DONE" "$PY scripts/planner_eval.py"
check planner_repro   "Planner evaluation reproduces the committed results"         "" "git diff --quiet -- results/planner_eval.json docs/PLANNER_EVAL.md"
check detector_eval   "Detector error analysis re-run (ground-truth totals gate)"   "ERROR ANALYSIS: DONE" "$PY scripts/detector_error_analysis.py"
check detector_repro  "Detector error analysis reproduces the committed results"    "" "git diff --quiet -- results/detector_error_analysis.json docs/DETECTOR_ANALYSIS.md"

{
  echo "# Verification (generated by scripts/verify_all.sh)"
  echo
  echo "Run on $STAMP | macOS $(sw_vers -productVersion 2>/dev/null) $(uname -m) | $("$J/bin/java" -version 2>&1 | head -1) | git $(git rev-parse --short HEAD)"
  echo
  echo "| check | result | time |"
  echo "|---|---|---:|"
  printf "%s" "$ROWS"
  echo
  echo "Passed: $NPASS | Failed: $NFAIL | total time $((SECONDS - T0)) s. Logs: logs/verify/ (not committed)."
} > docs/VERIFICATION.md

echo
echo "Passed: $NPASS | Failed: $NFAIL | total $((SECONDS - T0)) s"
if [ $NFAIL -ne 0 ]; then
  echo "VERIFY: $NFAIL CHECK(S) FAILED. Nothing committed. Send me this output."
  for n in $FAILED; do echo; echo "---- tail of logs/verify/$n.log ----"; tail -12 "logs/verify/$n.log"; done
  exit 1
fi
git add docs/VERIFICATION.md scripts/verify_all.sh
if git diff --cached --quiet; then
  echo "  nothing new to commit"
else
  git commit -q -m "docs: verification summary (all checks passed)" && echo "  committed: $(git log --oneline | head -1)"
fi
git push > build/_push_verify.txt 2>&1 && echo "  pushed ($(git status -sb | head -1))" || echo "  PUSH FAILED (see build/_push_verify.txt)"
echo "VERIFY: ALL CHECKS PASSED"
